const cheerio = require('cheerio');
function imageSizes(image, dimensions) {
  const style = image.attr('style') || '';
  const width = /(?:^|;)\s*width:\s*([\d.]+)(%|px)/i.exec(style)
    || /^(\d+(?:\.\d+)?)(%|px)?$/.exec(image.attr('width') || '');
  if (width) {
    if (width[2] === '%') {
      const ratio = Math.min(100, Number(width[1])) / 100;
      return `(max-width: 768px) calc((100vw - 66px) * ${ratio}), ${Math.round(900 * ratio)}px`;
    }
    return `(max-width: 768px) min(calc(100vw - 66px), ${width[1]}px), ${width[1]}px`;
  }
  const height = /(?:^|;)\s*height:\s*([\d.]+)px/i.exec(style);
  if (height) {
    const pixels = Math.round(Number(height[1]) * dimensions.width / dimensions.height);
    return `(max-width: 768px) min(calc(100vw - 66px), ${pixels}px), ${pixels}px`;
  }
  return '(max-width: 768px) calc(100vw - 66px), 900px';
}

function optimizePage(dom, previews) {
  // hexo-math injects both styles globally, even on pages without any math.
  // Include only the renderer actually present; assets come from installed
  // packages so their CSS matches the HTML generated by those packages.
  dom('link[rel="stylesheet"]').each((_, element) => {
    const link = dom(element);
    if (/\/npm\/(?:katex@[^/]+\/dist\/katex\.min\.css|hexo-math@[^/]+\/dist\/style\.css)/.test(link.attr('href') || '')) link.remove();
  });
  if (dom('.katex').length) dom('head').append('<link rel="stylesheet" href="/vendor/math/katex.min.css">');
  if (dom('mjx-container[jax="SVG"]').length) dom('head').append('<link rel="stylesheet" href="/vendor/math/svg.css">');

  // CSS background URLs otherwise become discoverable only after style/layout.
  const background = /url\(["']?([^"')]+)["']?\)/.exec(dom('#web_bg').attr('style') || '');
  if (background) {
    const preload = dom('<link rel="preload" as="image" fetchpriority="high">');
    preload.attr('href', background[1]);
    dom('head').prepend(preload);
  }

  // Restrict previews to article illustrations. Author sizing and original
  // assets are retained, and existing image links keep their destinations.
  dom('#post #article-container img').each((index, element) => {
    const image = dom(element);
    const source = image.attr('src') || '';
    image.attr('decoding', 'async');
    image.attr('loading', index === 0 ? 'eager' : 'lazy');
    if (index === 0) image.attr('fetchpriority', 'high');
    let key;
    try { key = decodeURIComponent(source.split('?')[0]); } catch { return; }
    const data = previews.get(key);
    if (!data || image.attr('srcset') || image.closest('picture').length) return;
    const variants = new Map([[data.width, { url: source, width: data.width }]]);
    for (const variant of data.variants) variants.set(variant.width, variant);
    if (!data.variants.length) return;
    image.attr('srcset', [...variants.values()].sort((a, b) => a.width - b.width)
      .map(variant => `${encodeURI(decodeURI(variant.url)).replace(/,/g, '%2C')} ${variant.width}w`).join(', '));
    image.attr('sizes', imageSizes(image, data));
    // Aspect ratio reserves space without replacing percentage or fixed-height
    // sizing already chosen by the author.
    if (!/aspect-ratio\s*:/i.test(image.attr('style') || '')) {
      image.attr('style', `${image.attr('style') || ''}; aspect-ratio: ${data.width} / ${data.height}`);
    }
  });

  // Homepage lists and sidebars must not compete with the above-fold images.
  dom('#recent-posts .post_cover img, #aside-content img, #archive img, #tag img, #category img')
    .attr('loading', 'lazy').attr('decoding', 'async');
  dom('#recent-posts .post_cover img').first().attr('loading', 'eager');
}

// Windows image encoder, materialized only in the system temporary cache.
const previewScript = String.raw`param([Parameter(Mandatory = $true)][string]$JobFile)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$jobs = Get-Content -LiteralPath $JobFile -Raw -Encoding UTF8 | ConvertFrom-Json
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System;
using System.Drawing;
using System.Drawing.Imaging;
using System.Runtime.InteropServices;
public static class BlogImageAlpha {
    public static bool HasTransparency(Image image) {
        if (!Image.IsAlphaPixelFormat(image.PixelFormat) &&
            (image.PixelFormat & PixelFormat.Indexed) == 0) return false;
        using (var bitmap = new Bitmap(image)) {
            var rectangle = new Rectangle(0, 0, bitmap.Width, bitmap.Height);
            var data = bitmap.LockBits(rectangle, ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
            try {
                var row = new byte[bitmap.Width * 4];
                for (int y = 0; y < bitmap.Height; y++) {
                    Marshal.Copy(IntPtr.Add(data.Scan0, y * data.Stride), row, 0, row.Length);
                    for (int i = 3; i < row.Length; i += 4)
                        if (row[i] < 255) return true;
                }
                return false;
            } finally { bitmap.UnlockBits(data); }
        }
    }
}
'@
$jpeg = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -EQ 'image/jpeg'
foreach ($job in $jobs) {
    $image = $null
    try {
        $image = [System.Drawing.Image]::FromFile($job.source)
        # Keep transparent diagrams lossless by retaining their original PNG.
        if ([BlogImageAlpha]::HasTransparency($image)) {
            [System.IO.File]::WriteAllText($job.done, 'transparent')
            continue
        }
        foreach ($variant in $job.variants) {
            $width = [int]$variant.width
            $height = [Math]::Max(1, [int][Math]::Round($image.Height * $width / $image.Width))
            $bitmap = [System.Drawing.Bitmap]::new($width, $height)
            $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
            $options = [System.Drawing.Imaging.EncoderParameters]::new(1)
            try {
                $graphics.Clear([System.Drawing.Color]::White)
                $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
                $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
                $graphics.DrawImage($image, 0, 0, $width, $height)
                $options.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, [long]88)
                $bitmap.Save($variant.file, $jpeg, $options)
            } finally {
                $options.Dispose()
                $graphics.Dispose()
                $bitmap.Dispose()
            }
        }
        [System.IO.File]::WriteAllText($job.done, 'ok')
    } catch {
        [Console]::Error.WriteLine('Preview skipped: ' + $job.source + ': ' + $_.Exception.Message)
    } finally {
        if ($image) { $image.Dispose() }
    }
}`;

const cache = path.join(require('node:os').tmpdir(), 'hexo-blog-images-' +
  crypto.createHash('sha256').update(hexo.base_dir).digest('hex').slice(0, 12));
let previews = new Map();
let routes = [];

function preparePreviews() {
  previews = new Map();
  routes = [];
  fs.mkdirSync(cache, { recursive: true });
  const inputs = [];
  const walk = directory => {
    if (!fs.existsSync(directory)) return;
    for (const file of fs.readdirSync(directory, { withFileTypes: true })) {
      const source = path.join(directory, file.name);
      if (file.isDirectory()) walk(source);
      else if (/\.(png|jpe?g)$/i.test(file.name)) inputs.push(source);
    }
  };
  walk(path.join(hexo.source_dir, 'illustrations'));
  const jobs = [];
  const entries = [];
  for (const source of inputs) {
    const bytes = fs.readFileSync(source);
    if (bytes.length < 32 * 1024) continue;
    let dimensions;
    try { dimensions = imageSize(bytes); } catch { continue; }
    if (dimensions.orientation && dimensions.orientation !== 1) continue;
    const { width, height } = dimensions;
    const hash = crypto.createHash('sha256').update('blog-preview-v1-q88').update(bytes).digest('hex').slice(0, 24);
    const done = path.join(cache, `${hash}.done`);
    const variants = [...new Set([480, 960, 1440].map(size => Math.min(width, size)))].map(size => ({
      width: size,
      url: `/previews/${hash}-${size}.jpg`,
      file: path.join(cache, `${hash}-${size}.jpg`)
    }));
    const job = { source, done, variants };
    if (!fs.existsSync(done)) jobs.push(job);
    entries.push({ source, width, height, bytes: bytes.length, variants });
  }
  if (jobs.length && process.platform === 'win32') {
    const jobFile = path.join(cache, 'jobs.json');
    fs.writeFileSync(jobFile, JSON.stringify(jobs));
    const scriptFile = path.join(cache, 'generate.ps1');
    fs.writeFileSync(scriptFile, previewScript);
    hexo.log.info(`Generating article image previews (${jobs.length} changed images)`);
    execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
      '-File', scriptFile, '-JobFile', jobFile],
    { windowsHide: true, timeout: 180000, stdio: ['ignore', 'ignore', 'inherit'] });
  } else if (jobs.length) {
    hexo.log.warn('Image preview generation needs Windows System.Drawing; using cached previews or original images.');
  }
  for (const entry of entries) {
    const variants = entry.variants.filter(variant => fs.existsSync(variant.file)
      && fs.statSync(variant.file).size < entry.bytes * 0.85);
    const url = '/' + path.relative(hexo.source_dir, entry.source).split(path.sep).join('/');
    previews.set(url, { ...entry, variants });
    for (const variant of variants) routes.push({ path: variant.url.slice(1), data: () => fs.createReadStream(variant.file) });
  }
}

hexo.extend.filter.register('before_generate', preparePreviews, 8);
hexo.extend.generator.register('article-image-previews', () => routes);
hexo.extend.generator.register('local-math-styles', () => {
  const katex = path.dirname(require.resolve('katex'));
  const fonts = path.join(katex, 'fonts');
  return [
    { path: 'vendor/math/katex.min.css', data: fs.readFileSync(path.join(katex, 'katex.min.css')) },
    { path: 'vendor/math/svg.css', data: fs.readFileSync(path.join(path.dirname(require.resolve('hexo-math')), 'dist/style.css')) },
    ...fs.readdirSync(fonts).map(name => ({ path: `vendor/math/fonts/${name}`, data: () => fs.createReadStream(path.join(fonts, name)) }))
  ];
});
hexo.extend.filter.register('after_render:html', html => {
  const dom = cheerio.load(html, { decodeEntities: false });
  optimizePage(dom, previews);
  return dom.html();
}, 30);
